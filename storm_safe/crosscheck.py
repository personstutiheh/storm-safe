"""Cross-check: Python guard vs the verified Promela guard model.

Builds one Promela program containing the verified model's own text (mtype,
apply, violates), runs many random scenarios through it with `spin` (simulation,
no compile), and compares every decision with storm_safe/guard.py.
"""
import argparse
import os
import random
import re
import subprocess
from collections import Counter
from pathlib import Path

from storm_safe.guard import check_sequence

ROOT = Path(__file__).resolve().parent.parent
MODEL = ROOT / "promela" / "storm_safe_guarded.pml"
BUILD = ROOT / "build"
MAXLEN = 5

# (Python command, Promela name). The model has fixed burns: 5 km and 25 km.
VARIANTS = [
    ({"name": "enter_safe_mode"}, "enter_safe_mode"),
    ({"name": "hibernate_payload"}, "hibernate_payload"),
    ({"name": "activate_payload"}, "activate_payload"),
    ({"name": "reorient_panels", "params": {"angle_deg": 10}}, "reorient_panels"),
    ({"name": "adjust_antenna_gain", "params": {"level": "low"}}, "antenna_low"),
    ({"name": "adjust_antenna_gain", "params": {"level": "normal"}}, "antenna_normal"),
    ({"name": "adjust_antenna_gain", "params": {"level": "high"}}, "antenna_high"),
    ({"name": "raise_orbit", "params": {"delta_km": 5}}, "raise_orbit_small"),
    ({"name": "raise_orbit", "params": {"delta_km": 25}}, "raise_orbit_big"),
    ({"name": "no_action"}, "no_action"),
]

def extract_block(text, pattern):
    """Return the text from `pattern` through its matching closing brace."""
    m = re.search(pattern, text)
    if not m:
        raise ValueError(f"pattern not found in model: {pattern}")
    i = text.index("{", m.end())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[m.start(): j + 1]
    raise ValueError(f"unbalanced braces after: {pattern}")

def make_cases(n, seed):
    rng = random.Random(seed)
    powers = [0, 10, 14, 15, 16, 20, 25, 30, 35, 39, 40, 41, 50, 60, 80, 95, 100]
    fuels = [0, 10, 20, 25, 30, 40, 50, 60, 70, 100]
    cases = []
    for _ in range(n):
        state = {
            "mode": rng.choice(["normal", "degraded", "safe"]),
            "payload_on": rng.random() < 0.5,
            "power": rng.choice(powers) if rng.random() < 0.7 else rng.randint(0, 100),
            "fuel": rng.choice(fuels) if rng.random() < 0.7 else rng.randint(0, 100),
        }
        cond = {"high_radiation": rng.random() < 0.5, "severe_storm": rng.random() < 0.5}
        picks = [rng.choice(VARIANTS) for _ in range(rng.randint(1, MAXLEN))]
        cases.append({
            "state": state,
            "cond": cond,
            "commands": [p[0] for p in picks],
            "pcmds": [p[1] for p in picks],
        })
    return cases

def build_program(cases):
    text = MODEL.read_text()
    mtype = extract_block(text, r"mtype\s*=\s*") + ";"
    apply_inline = extract_block(text, r"inline\s+apply\s*\(")
    violates_inline = extract_block(text, r"inline\s+violates\s*\(")
    n = len(cases)

    data = []
    for k, c in enumerate(cases):
        st, cd = c["state"], c["cond"]
        data.append(
            f"  imode[{k}] = {st['mode']}; ipay[{k}] = {int(st['payload_on'])}; "
            f"ipower[{k}] = {st['power']}; ifuel[{k}] = {st['fuel']}; "
            f"ihr[{k}] = {int(cd['high_radiation'])}; iss[{k}] = {int(cd['severe_storm'])}; "
            f"ilen[{k}] = {len(c['pcmds'])};")
        for j, name in enumerate(c["pcmds"]):
            data.append(f"  icmd[{k * MAXLEN + j}] = {name};")

    return f"""/* GENERATED by storm_safe/crosscheck.py -- do not edit. */
{mtype}

mtype mode = normal;
bool payload_on = true;
short power = 80;
short fuel = 60;
bool high_radiation = false;
bool severe_storm = false;
bool bad = false;

{apply_inline}

{violates_inline}

mtype imode[{n}];
bool ipay[{n}];
bool ihr[{n}];
bool iss[{n}];
short ipower[{n}];
short ifuel[{n}];
short ilen[{n}];
mtype icmd[{n * MAXLEN}];

active proctype oracle() {{
  mtype c, pre_mode, old_mode;
  bool old_payload, acc;
  short old_power, old_fuel;
  short k, j;
{chr(10).join(data)}
  k = 0;
  do
  :: k < {n} ->
       mode = imode[k]; payload_on = ipay[k]; power = ipower[k]; fuel = ifuel[k];
       high_radiation = ihr[k]; severe_storm = iss[k];
       printf("CASE %d\\n", k);
       j = 0;
       do
       :: j < ilen[k] ->
            c = icmd[k * {MAXLEN} + j];
            pre_mode = mode; old_mode = mode; old_payload = payload_on;
            old_power = power; old_fuel = fuel;
            apply(c);
            violates(c, pre_mode);
            if
            :: bad -> mode = old_mode; payload_on = old_payload;
                      power = old_power; fuel = old_fuel; acc = 0
            :: else -> acc = 1
            fi;
            printf("STEP %d %e\\n", acc, c);
            j++
       :: else -> break
       od;
       /* R6 once, at the end of the plan (same as guard.py) */
       if
       :: (severe_storm && mode != safe) -> apply(enter_safe_mode); printf("ADD enter_safe_mode\\n")
       :: else -> skip
       fi;
       if
       :: (high_radiation && payload_on) -> apply(hibernate_payload); printf("ADD hibernate_payload\\n")
       :: else -> skip
       fi;
       printf("END %e %d %d %d\\n", mode, payload_on, power, fuel);
       k++
  :: else -> break
  od
}}
"""

def _spin_cmd(path):
    p = str(path)
    if os.name == "nt":  # run SPIN through WSL
        drive, rest = os.path.splitdrive(p)
        return ["wsl", "spin", "-u10000000", f"/mnt/{drive[0].lower()}{rest.replace(chr(92), '/')}"]
    return ["spin", "-u10000000", p]

def spin_available():
    cmd = ["wsl", "spin", "-V"] if os.name == "nt" else ["spin", "-V"]
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=60,
                           encoding="utf-8", errors="replace")
        return "Spin Version" in (r.stdout + r.stderr)
    except Exception:
        return False

def run_spin(program):
    BUILD.mkdir(exist_ok=True)
    path = BUILD / "xcheck.pml"
    path.write_text(program)
    r = subprocess.run(_spin_cmd(path), capture_output=True, text=True, timeout=600,
                       encoding="utf-8", errors="replace")
    if "error" in r.stderr.lower() and "CASE" not in r.stdout:
        raise RuntimeError("SPIN failed:\n" + r.stderr[:2000] + r.stdout[:2000])
    return r.stdout

def parse(output):
    cases, cur = [], None
    for line in output.splitlines():
        s = line.strip()
        if s.startswith("CASE "):
            cur = {"accepted": [], "commands": [], "added": [], "end": None}
            cases.append(cur)
        elif cur is None:
            continue
        elif s.startswith("STEP "):
            _, acc, name = s.split()
            cur["accepted"].append(acc == "1")
            cur["commands"].append(name)
        elif s.startswith("ADD "):
            cur["added"].append(s.split()[1])
        elif s.startswith("END "):
            _, m, pay, pw, fu = s.split()
            cur["end"] = {"mode": m, "payload_on": pay == "1",
                          "power": int(pw), "fuel": int(fu)}
    return cases

def python_result(case):
    out = check_sequence(case["state"], case["cond"], case["commands"])
    return {
        "accepted": [r["accepted"] for r in out["results"]],
        "added": [a["command"]["name"] for a in out["guard_added"]],
        "end": out["final_state"],
        "rules": [v["rule"] for r in out["results"] for v in r["violations"]],
    }

def run(n=300, seed=1):
    cases = make_cases(n, seed)
    promela = parse(run_spin(build_program(cases)))
    if len(promela) != n:
        raise RuntimeError(f"expected {n} cases from SPIN, parsed {len(promela)}")
    mismatches, coverage = [], Counter()
    for i, (case, pml) in enumerate(zip(cases, promela)):
        py = python_result(case)
        coverage.update(py["rules"])
        coverage.update("R6:" + a for a in py["added"])
        same = (py["accepted"] == pml["accepted"]
                and py["added"] == pml["added"]
                and pml["end"] is not None
                and all(py["end"][k] == pml["end"][k]
                        for k in ("mode", "payload_on", "power", "fuel")))
        if not same:
            mismatches.append({
                "case": i, "state": case["state"], "cond": case["cond"],
                "commands": case["pcmds"], "python": py, "promela": pml})
    return {"cases": n, "mismatches": mismatches, "coverage": coverage}

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=300)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    rep = run(args.n, args.seed)
    print(f"cases: {rep['cases']}  mismatches: {len(rep['mismatches'])}")
    print("coverage:", dict(sorted(rep["coverage"].items())))
    for m in rep["mismatches"][:3]:
        print("MISMATCH", m)